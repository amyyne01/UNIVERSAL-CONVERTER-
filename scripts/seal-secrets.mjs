// Build-time sealer for the licence client's two credentials. Holds no secret.
//   node scripts/seal-secrets.mjs --env <file> [--out <path>]
//   node scripts/seal-secrets.mjs --dummy [--out <path>]
// Writes a Rust file with `PAD` and `MASKED` (136 bytes each). The plain record is
// [version=1][token len][token][id len][id][random filler] to 128 bytes, then the
// first 8 bytes of its SHA-256; MASKED = record+tag XOR a fresh random PAD.
// Nothing is kept between runs: the pad exists only in the output file.
import { createHash, randomBytes } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';

const TOKEN_KEY = 'LICENSE_TOKEN';
const ID_KEY = 'LICENSE_REGISTRY_ID';
const DEFAULT_OUT = 'crates/ahg-app/src/secrets.gen.rs';
const DUMMY_OUT = 'crates/ahg-runtime/tests/fixtures/sealed-dummy.rs';

const fail = (msg) => {
  console.error(`seal-secrets: ${msg}`); // never put a value in a message
  process.exit(1);
};

const args = process.argv.slice(2);
const flag = (n) => args.includes(n);
const opt = (n) => (args.includes(n) ? args[args.indexOf(n) + 1] : undefined);
const dummy = flag('--dummy');
const out = opt('--out') ?? (dummy ? DUMMY_OUT : DEFAULT_OUT);
const envPath = opt('--env');
if (!out) fail('--out needs a path');
if (!dummy && !envPath) fail('give --env <file> (or --dummy)');

// Real mode: the output must be git-ignored (exit 0). Anything else, including
// "not a repository" (128), refuses. Dummy mode holds no secret, so it is exempt.
if (!dummy) {
  const r = spawnSync('git', ['check-ignore', '-q', out]);
  if (r.status !== 0) fail(`refusing to write ${out}: not git-ignored`);
}

let token, id;
if (dummy) {
  token = 'dummy-token-0000-not-a-secret';
  id = 'dummy-id-1111-not-a-secret';
} else {
  const text = readFileSync(envPath, 'utf8');
  let vals;
  if (text.trimStart().startsWith('{')) {
    vals = JSON.parse(text);
  } else {
    vals = {};
    for (const line of text.split(/\r?\n/)) {
      const m = /^\s*([A-Za-z0-9_]+)\s*=\s*(.*?)\s*$/.exec(line);
      if (m) vals[m[1]] = m[2].replace(/^(["'])(.*)\1$/, '$2');
    }
  }
  token = vals[TOKEN_KEY];
  id = vals[ID_KEY];
}
if (typeof token !== 'string' || typeof id !== 'string' || !token || !id) {
  fail(`${TOKEN_KEY} and ${ID_KEY} must both be present and non-empty`);
}

const t = Buffer.from(token, 'utf8');
const i = Buffer.from(id, 'utf8');
if (2 + t.length + 1 + i.length > 128) fail('values too long for the 128-byte record');

const plain = Buffer.concat([Buffer.from([1, t.length]), t, Buffer.from([i.length]), i]);
const record = Buffer.concat([plain, randomBytes(128 - plain.length)]);
const tagged = Buffer.concat([record, createHash('sha256').update(record).digest().subarray(0, 8)]);
const pad = randomBytes(136);
const masked = Buffer.from(tagged.map((b, k) => b ^ pad[k]));

const arr = (name, buf) => {
  const rows = [];
  for (let k = 0; k < 136; k += 16) {
    rows.push('    ' + [...buf.subarray(k, k + 16)].map((b) => '0x' + b.toString(16).padStart(2, '0')).join(', ') + ',');
  }
  return `pub static ${name}: [u8; 136] = [\n${rows.join('\n')}\n];\n`;
};
writeFileSync(out, `// Generated by scripts/seal-secrets.mjs. Do not edit.\n${arr('PAD', pad)}${arr('MASKED', masked)}`);
console.log(`seal-secrets: wrote ${out}`);
